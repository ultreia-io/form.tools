#' Export statuses
#'
#' Export declarations use status strings in YAML. Field callbacks can return
#' status strings with a value, message or details.
#'
#' @section Declaration statuses:
#' - `specified` (`EXPORT_DECLARATION_STATUS_SPECIFIED`) runs the rule.
#' - `pending` (`EXPORT_DECLARATION_STATUS_PENDING`) skips a rule awaiting implementation
#'   or a decision and reports a diagnostic.
#' - `unavailable` (`EXPORT_DECLARATION_STATUS_UNAVAILABLE`) skips a rule with
#'   unavailable source information and reports a diagnostic.
#' - `omitted` (`EXPORT_DECLARATION_STATUS_OMITTED`) leaves a field blank or
#'   a table empty without a diagnostic.
#'
#' @section Field callback statuses:
#' - `resolved` (`EXPORT_RESULT_STATUS_RESOLVED`) supplies a value.
#' - `omitted` (`EXPORT_RESULT_STATUS_OMITTED`) returns an intentional blank
#'   without a diagnostic.
#' - `unresolved` (`EXPORT_RESULT_STATUS_UNRESOLVED`) leaves the field blank
#'   and reports a blocking diagnostic.
#' - `warning` (`EXPORT_RESULT_STATUS_WARNING`) keeps the value and reports
#'   a non-blocking diagnostic.
#'
#' @section Diagnostics generated by the engine:
#' - `missing_value` (`EXPORT_RESULT_STATUS_MISSING_VALUE`) indicates a missing
#'   mandatory value.
#' - `invalid_value` (`EXPORT_RESULT_STATUS_INVALID_VALUE`) indicates a fixed-cell
#'   input that does not match its declared type.
#' - `rule_error` (`EXPORT_RESULT_STATUS_RULE_ERROR`) indicates an error
#'   while evaluating a rule or checking its result.
#'
#' @format Character constants.
#' @seealso [prepare_form_export()], [run_form_export()]
#' @name export_status_constants
NULL

